COMBO_DISCOUNT = '''任务：根据优惠规则计算实付金额。
规则：满 200 减 30，满 300 减 50，不可叠加；会员再 9 折，与满减可叠加。

示例1：
问题：订单 250 元，是会员。
推理：
1. 满 200 减 30 适用，满 300 不适用
2. 取满 200 减 30：250 - 30 = 220
3. 会员 9 折：220 × 0.9 = 198
答案：198 元

示例2：
问题：订单 350 元，非会员。
推理：
1. 满 300 减 50 适用（优于满 200 减 30）
2. 350 - 50 = 300
3. 非会员不打折
答案：300 元

问题：订单 180 元，是会员。
推理：'''

